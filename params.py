def seasons_for(region):
    """Границы сезонов региона; для нового региона — значения по умолчанию."""
    if region not in SEASONS:
        SEASONS[region] = dict(SEASONS_TEMPLATE)
    return SEASONS[region]


def season_months(region, key):
    """Список номеров месяцев сезона (с учётом перехода через новый год)."""
    a, b = seasons_for(region)[key]
    return list(range(a, b + 1)) if a <= b else list(range(a, 13)) + list(range(1, b + 1))
